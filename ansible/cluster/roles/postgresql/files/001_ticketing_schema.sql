BEGIN;
CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) NOT NULL UNIQUE, name VARCHAR(100) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(200) NOT NULL, venue VARCHAR(200) NOT NULL,
  starts_at TIMESTAMPTZ NOT NULL, booking_opens_at TIMESTAMPTZ,
  status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT events_status_check CHECK (status IN ('DRAFT','OPEN','CLOSED','CANCELLED'))
);
CREATE TABLE IF NOT EXISTS seats (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  seat_no VARCHAR(50) NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',
  price NUMERIC(12,2) NOT NULL CHECK (price >= 0), booked_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT seats_event_seat_no_unique UNIQUE (event_id,seat_no),
  CONSTRAINT seats_status_check CHECK (status IN ('AVAILABLE','BOOKED'))
);
CREATE TABLE IF NOT EXISTS bookings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id), event_id BIGINT NOT NULL REFERENCES events(id),
  status VARCHAR(20) NOT NULL DEFAULT 'PENDING', total_amount NUMERIC(12,2) NOT NULL CHECK (total_amount >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT bookings_status_check CHECK (status IN ('PENDING','CONFIRMED','CANCELLED'))
);
CREATE TABLE IF NOT EXISTS booking_seats (
  booking_id BIGINT NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  seat_id BIGINT NOT NULL REFERENCES seats(id), price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (booking_id,seat_id), CONSTRAINT booking_seats_seat_unique UNIQUE (seat_id)
);
CREATE TABLE IF NOT EXISTS payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id BIGINT NOT NULL UNIQUE REFERENCES bookings(id),
  idempotency_key VARCHAR(100) NOT NULL UNIQUE,
  amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0), status VARCHAR(20) NOT NULL DEFAULT 'READY',
  paid_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT payments_status_check CHECK (status IN ('READY','SUCCEEDED','FAILED','CANCELLED'))
);
CREATE TABLE IF NOT EXISTS processed_events (
  event_id VARCHAR(100) PRIMARY KEY, event_type VARCHAR(100) NOT NULL,
  processed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_seats_event_status ON seats(event_id,status);
CREATE INDEX IF NOT EXISTS idx_bookings_user_created ON bookings(user_id,created_at DESC);
CREATE INDEX IF NOT EXISTS idx_bookings_event ON bookings(event_id);
INSERT INTO schema_migrations(version,description) VALUES ('001','Initial ticketing database schema')
ON CONFLICT(version) DO NOTHING;
COMMIT;
